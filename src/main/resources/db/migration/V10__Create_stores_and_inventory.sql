CREATE TABLE IF NOT EXISTS public.stores (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name character varying(255) NOT NULL,
    province_code character varying(255),
    address text NOT NULL,
    phone character varying(50),
    latitude double precision NOT NULL,
    longitude double precision NOT NULL,
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamp(6) without time zone NOT NULL DEFAULT now(),
    updated_at timestamp(6) without time zone NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.store_inventory (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id integer NOT NULL REFERENCES public.stores (id) ON DELETE CASCADE,
    product_id integer NOT NULL REFERENCES public.products (id) ON DELETE CASCADE,
    amount integer NOT NULL DEFAULT 0 CHECK (amount >= 0),
    CONSTRAINT uq_store_inventory_store_product UNIQUE (store_id, product_id)
);

CREATE INDEX IF NOT EXISTS idx_store_inventory_product ON public.store_inventory (product_id);

ALTER TABLE public.orders
    ADD COLUMN IF NOT EXISTS store_id integer REFERENCES public.stores (id),
    ADD COLUMN IF NOT EXISTS shipping_fee numeric(10,2) NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS distance_km numeric(8,2);

ALTER TABLE public.shipping_addresses
    ADD COLUMN IF NOT EXISTS latitude double precision,
    ADD COLUMN IF NOT EXISTS longitude double precision;

